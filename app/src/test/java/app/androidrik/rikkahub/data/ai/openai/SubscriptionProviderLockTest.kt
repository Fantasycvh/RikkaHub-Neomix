package app.androidrik.rikkahub.data.ai.openai

import app.androidrik.ai.provider.Model
import app.androidrik.ai.provider.OpenAIAuthType
import app.androidrik.ai.provider.ProviderSetting
import kotlin.uuid.Uuid
import org.junit.Assert.assertEquals
import org.junit.Assert.assertFalse
import org.junit.Assert.assertNull
import org.junit.Assert.assertTrue
import org.junit.Test

/**
 * 订阅对话的提供商锁定：只允许同提供商换模型，不允许切到别家。
 *
 * 行为契约（都在 [resolveSubscriptionProviderLock] / [SubscriptionProviderLock] 里）：
 * 1. 历史里有订阅模型生成的消息 ⇒ 锁定；
 * 2. 历史里只有别家模型（哪怕当前选中了订阅模型）⇒ 不锁（否则助手级模型一改，
 *    所有历史对话都被锁死且切不回去）；
 * 3. 空对话 ⇒ 不锁；
 * 4. 停用的订阅提供商 / API Key 模式的 provider ⇒ 不参与锁定。
 */
class SubscriptionProviderLockTest {

    private val codexModel = Model(modelId = "gpt-6.1-sol", displayName = "GPT-6.1-Sol")
    private val codexModel2 = Model(modelId = "gpt-6-luna", displayName = "GPT-6-Luna")
    private val otherModel = Model(modelId = "deepseek-v4", displayName = "DeepSeek-V4")

    private fun subscriptionProvider(
        models: List<Model> = listOf(codexModel, codexModel2),
        enabled: Boolean = true,
        authType: OpenAIAuthType = OpenAIAuthType.CHATGPT_SUBSCRIPTION,
    ) = ProviderSetting.OpenAI(
        name = "OpenAI",
        enabled = enabled,
        authType = authType,
        models = models,
    )

    private fun apiKeyProvider(models: List<Model> = listOf(otherModel)) =
        ProviderSetting.OpenAI(name = "OpenAI API Key", models = models)

    @Test
    fun `conversation generated by subscription is locked`() {
        val subscription = subscriptionProvider()
        val lock = resolveSubscriptionProviderLock(
            providers = listOf(subscription, apiKeyProvider()),
            historyModelIds = listOf(codexModel.id),
        )

        assertEquals(subscription.id, lock?.providerId)
        assertEquals("OpenAI", lock?.providerName)
    }

    @Test
    fun `same provider keeps switching allowed`() {
        val subscription = subscriptionProvider()
        val providers = listOf(subscription)
        val lock = resolveSubscriptionProviderLock(providers, listOf(codexModel.id))!!

        assertTrue(lock.allows(codexModel2, providers))
        assertFalse(lock.allows(otherModel, providers))
    }

    @Test
    fun `history from other providers does not lock even if subscription model selected`() {
        assertNull(
            resolveSubscriptionProviderLock(
                providers = listOf(subscriptionProvider(), apiKeyProvider()),
                historyModelIds = listOf(otherModel.id),
            )
        )
    }

    @Test
    fun `empty conversation is not locked`() {
        assertNull(
            resolveSubscriptionProviderLock(
                providers = listOf(subscriptionProvider()),
                historyModelIds = emptyList(),
            )
        )
    }

    @Test
    fun `disabled subscription provider does not lock`() {
        assertNull(
            resolveSubscriptionProviderLock(
                providers = listOf(subscriptionProvider(enabled = false)),
                historyModelIds = listOf(codexModel.id),
            )
        )
    }

    @Test
    fun `api key provider never locks`() {
        assertNull(
            resolveSubscriptionProviderLock(
                providers = listOf(apiKeyProvider(models = listOf(codexModel))),
                historyModelIds = listOf(codexModel.id),
            )
        )
    }

    @Test
    fun `filterProviders keeps only the locked provider`() {
        val subscription = subscriptionProvider()
        val providers = listOf(subscription, apiKeyProvider())
        val lock = resolveSubscriptionProviderLock(providers, listOf(codexModel.id))!!

        assertEquals(listOf(subscription.id), lock.filterProviders(providers).map { it.id })
    }

    @Test
    fun `unknown model id is rejected by allows`() {
        val subscription = subscriptionProvider()
        val providers = listOf(subscription)
        val lock = resolveSubscriptionProviderLock(providers, listOf(codexModel.id))!!

        assertFalse(lock.allows(Model(modelId = "ghost", displayName = "Ghost"), providers))
    }

    @Test
    fun `history with trailing user message stays locked`() {
        val subscription = subscriptionProvider()
        val providers = listOf(subscription)
        // 用户已发下一条消息（modelId 为 null，调用方会过滤掉），历史里仍有订阅回复
        val lock = resolveSubscriptionProviderLock(
            providers = providers,
            historyModelIds = listOf(codexModel.id, Uuid.random()),
        )!!
        assertEquals(subscription.id, lock.providerId)
    }

    @Test
    fun `unlocked conversation always allows sending`() {
        val providers = listOf(subscriptionProvider(), apiKeyProvider())

        assertTrue(
            resolveSubscriptionProviderLock(providers, emptyList())
                .allowsSendingWith(otherModel, providers)
        )
    }

    @Test
    fun `locked conversation blocks sending with a foreign provider model`() {
        val providers = listOf(subscriptionProvider(), apiKeyProvider())
        val lock = resolveSubscriptionProviderLock(providers, listOf(codexModel.id))

        assertFalse(lock.allowsSendingWith(otherModel, providers))
        assertTrue(lock.allowsSendingWith(codexModel, providers))
    }

    @Test
    fun `locked conversation allows sending when model is temporarily unknown`() {
        val providers = listOf(subscriptionProvider())
        val lock = resolveSubscriptionProviderLock(providers, listOf(codexModel.id))

        // 模型解析失败时不拦发送：服务端/下层会给出更准确的报错，避免 UI 静默踢回
        assertTrue(lock.allowsSendingWith(null, providers))
    }
}
